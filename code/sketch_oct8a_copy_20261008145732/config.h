#define I2S_DIN  7

// ---- 一颗电源指示灯（2026-10-27 改）----
// 用户决定：三色灯不要了，只留一颗，**只用来指示开关机**（通电常亮）。
// 所以平台下发的 LED_GREEN_ON / LED_BLUE_ON / LED_RED_ON 现在不再驱动硬件，
// 只在串口里留个记录 —— 平台侧不用改，返回值照旧。
// 接线：GPIO --(220Ω)--> LED 长脚(阳极)；短脚 --> GND
#define LED_POWER_PIN 11

// ---- 屏幕显示（2026-10-15 加：拍照片/录视频更好看，也更好排障 ✓）----
#define BOOT_SPLASH_MS 1600    // 开机大字画面停留多久（足够拍照 ✓）
#define VOL_BAR_MS     2500    // 音量条显示多久（网页调音量时看得见 ✓）
#define SHOW_WIFI_RSSI 1       // 1 = 右上角画 Wi-Fi 信号格 ✓（演示时一眼看出还连着网 ✓）

// ================= 外接实体按键（2026-11-02，盒子封了 BOOT/RESET 之后）=================
// 为什么用它：板子装进盒子，板载 BOOT(IO0) 和 RESET 都按不到 ✗。
// 接线（最简单，三个元件都不需要）：
//   轻触开关 一脚 → GND        另一脚 → BUTTON2_PIN
//   固件用**内部上拉**，按下就是接地（低电平）✓ 不用外接电阻
// 功能：
//   短按        = 说一句（等同按 BOOT）
//   长按 3 秒   = 重启（等同按 RESET）
//   按下瞬间电源灯闪一下 = 唯一的即时反馈（封盒后看不见别的）
//
// ⚠️ 选脚注意：下面这些别用
//   · 已被占用：0(BOOT) 5/6/7(功放 I2S) 11(电源灯) 15/16/17(麦克风)
//   · USB：19/20      · 片内 flash/PSRAM：26~37
//   · 上电会决定启动模式的 strapping 脚：0 / 3 / 45 / 46
//   推荐：4 / 8 / 9 / 10 / 21 / 47（原来 OLED 用的 47 和 21 现在正好空着）
#define BUTTON2_ENABLED      1     // 0 = 不用外接按键
#define BUTTON2_PIN          21    // 2026-11-02 定了：用 IO21（原来 OLED 的 SDA，已空出来）
#define BUTTON2_LONGPRESS_MS 3000  // 按住多久算"要重启"
#define BUTTON2_DEBOUNCE_MS  40    // 消抖（低于这个时长的按下不算）
